#!/bin/bash
# Builds the Linux agent binary and writes verified release artifacts into ./releases.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
VERSION=${VERSION:-0.5.0}
OUT="$ROOT/releases"
PUBLIC_URL=${FAMILY_VPN_PUBLIC_URL:-https://panel.example.com}
PUBLIC_URL=${PUBLIC_URL%/}
case "$PUBLIC_URL" in
  https://*|http://127.0.0.1|http://127.0.0.1:*|http://localhost|http://localhost:*) ;;
  http://*)
    echo "FAMILY_VPN_PUBLIC_URL: plain HTTP is only allowed for 127.0.0.1 or localhost" >&2
    exit 1
    ;;
  *)
    echo "FAMILY_VPN_PUBLIC_URL must start with https://" >&2
    exit 1
    ;;
esac
case "${PUBLIC_URL#*://}" in
  ""|*/*|*"@"*|*"?"*|*"#"*)
    echo "FAMILY_VPN_PUBLIC_URL must be an origin without a path" >&2
    exit 1
    ;;
esac
AGENT_NAME=family-vpn-agent-linux-amd64

mkdir -p "$OUT"
rm -f "$OUT/$AGENT_NAME" "$OUT/install.sh" "$OUT/install.sh.sig" "$OUT/release-signing.pub" \
  "$OUT/SHA256SUMS" "$OUT/INSTALL.txt" "$OUT/bootstrap.sh"

if ! command -v go >/dev/null; then
  echo "go is required to build the agent" >&2
  exit 1
fi

(
  cd "$ROOT/agent"
  GOOS=linux GOARCH=amd64 CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o "$OUT/$AGENT_NAME" .
)

install -m 0755 "$ROOT/installer/install.sh" "$OUT/install.sh"

PUB_SRC="$ROOT/keys/release-signing.pub"
[ -f "$PUB_SRC" ] || {
  echo "missing $PUB_SRC — commit the release public key" >&2
  exit 1
}
install -m 0644 "$PUB_SRC" "$OUT/release-signing.pub"
PUB_FP=$(sha256sum "$OUT/release-signing.pub" | awk '{ print $1 }')

# Production releases must always be signed. No unsigned publish path.
if [ -z "${FAMILY_VPN_RELEASE_SIGNING_KEY:-}" ] \
  && [ ! -f "$ROOT/keys/release-signing.pem" ] \
  && [ -z "${FAMILY_VPN_RELEASE_SIGNING_KEY_FILE:-}" ]; then
  echo "production release signing key required" >&2
  echo "set FAMILY_VPN_RELEASE_SIGNING_KEY, FAMILY_VPN_RELEASE_SIGNING_KEY_FILE, or keys/release-signing.pem" >&2
  exit 1
fi
if ! command -v node >/dev/null; then
  echo "node is required to sign release artifacts" >&2
  exit 1
fi
node "$ROOT/scripts/sign-release-file.mjs" "$OUT/install.sh"
node "$ROOT/scripts/verify-release-file.mjs" "$OUT/install.sh" "$OUT/install.sh.sig" "$OUT/release-signing.pub" "$PUB_FP"

# Portable checksum lines: "<hash><two spaces><name>" even under MSYS binary mode.
: > "$OUT/SHA256SUMS"
for file in "$AGENT_NAME" install.sh release-signing.pub; do
  [ -f "$OUT/$file" ] || continue
  hash=$(sha256sum "$OUT/$file" | awk '{ print $1 }')
  printf '%s  %s\n' "$hash" "$file" >> "$OUT/SHA256SUMS"
done
if [ -f "$OUT/install.sh.sig" ]; then
  hash=$(sha256sum "$OUT/install.sh.sig" | awk '{ print $1 }')
  printf '%s  %s\n' "$hash" "install.sh.sig" >> "$OUT/SHA256SUMS"
fi

INSTALL_SHA=$(awk '$2 == "install.sh" { print $1; exit }' "$OUT/SHA256SUMS")
AGENT_SHA=$(awk -v name="$AGENT_NAME" '$2 == name { print $1; exit }' "$OUT/SHA256SUMS")
[ -n "$INSTALL_SHA" ] && [ -n "$AGENT_SHA" ] || {
  echo "failed to read release checksums" >&2
  exit 1
}

[ -f "$OUT/install.sh.sig" ] || {
  echo "install.sh.sig missing; refusing to publish an unsigned bootstrap" >&2
  exit 1
}

# bootstrap.sh embeds the pubkey fingerprint from the committed keys/release-signing.pub.
# Signature verification is mandatory before install.sh is executed.
cat > "$OUT/bootstrap.sh" <<EOF
#!/bin/bash
# Generated by scripts/build-release.sh for Family VPN $VERSION
# Verifies install.sh (Ed25519 + pinned pubkey fingerprint + SHA-256) before exec.
set -euo pipefail
BACKEND="${PUBLIC_URL}"
EXPECTED_INSTALL_SHA="${INSTALL_SHA}"
EXPECTED_PUB_FP="${PUB_FP}"
umask 077
TMP=\$(mktemp -d)
trap 'rm -rf "\$TMP"' EXIT
curl -fsSL "\$BACKEND/releases/install.sh" -o "\$TMP/install.sh"
curl -fsSL "\$BACKEND/releases/install.sh.sig" -o "\$TMP/install.sh.sig"
curl -fsSL "\$BACKEND/releases/release-signing.pub" -o "\$TMP/release-signing.pub"
GOT=\$(sha256sum "\$TMP/install.sh" | awk '{print \$1}')
[ "\$GOT" = "\$EXPECTED_INSTALL_SHA" ] || {
  echo "family-vpn-bootstrap: install.sh checksum mismatch" >&2
  exit 1
}
echo "\$EXPECTED_PUB_FP  \$TMP/release-signing.pub" | sha256sum -c -
SIG_B64=\$(tr -d '\\n' <"\$TMP/install.sh.sig" | tr '_-' '/+')
case \$(( \${#SIG_B64} % 4 )) in
  2) SIG_B64="\${SIG_B64}==" ;;
  3) SIG_B64="\${SIG_B64}=" ;;
esac
printf '%s' "\$SIG_B64" | openssl base64 -d -A -out "\$TMP/sig.bin"
openssl pkeyutl -verify -pubin -inkey "\$TMP/release-signing.pub" -rawin -in "\$TMP/install.sh" -sigfile "\$TMP/sig.bin" >/dev/null || {
  echo "family-vpn-bootstrap: install.sh signature rejected" >&2
  exit 1
}
exec bash "\$TMP/install.sh" --backend "\$BACKEND" "\$@"
EOF
chmod 0755 "$OUT/bootstrap.sh"

BOOT_SHA=$(sha256sum "$OUT/bootstrap.sh" | awk '{ print $1 }')
printf '%s  %s\n' "$BOOT_SHA" "bootstrap.sh" >> "$OUT/SHA256SUMS"

# One-liner: download bootstrap, verify its SHA-256 (shown in panel UI), then run it.
# bootstrap itself verifies install.sh signature against the pinned pubkey fingerprint.
ONE_COMMAND="curl -fsSL ${PUBLIC_URL}/releases/bootstrap.sh -o /tmp/fvpn-boot.sh && echo '${BOOT_SHA}  /tmp/fvpn-boot.sh' | sha256sum -c - && sudo bash /tmp/fvpn-boot.sh"
UPDATE_COMMAND="curl -fsSL ${PUBLIC_URL}/releases/bootstrap.sh -o /tmp/fvpn-boot.sh && echo '${BOOT_SHA}  /tmp/fvpn-boot.sh' | sha256sum -c - && sudo bash /tmp/fvpn-boot.sh --update"

cat > "$OUT/INSTALL.txt" <<EOF
Family VPN agent release $VERSION

Preferred one-line install (Ed25519 signature + pinned pubkey fingerprint + SHA-256):

${ONE_COMMAND}

Safe one-line update for an already paired agent (keeps agent.json, wg0.conf, peers, keys, NAT):

${UPDATE_COMMAND}

Public key fingerprint (SHA-256 of release-signing.pub): ${PUB_FP}
install.sh then downloads ${AGENT_NAME} from the same origin and verifies SHA256SUMS before changing the system.
Remote panels require HTTPS. Plain HTTP is accepted only for 127.0.0.1 or localhost through a trusted SSH tunnel.

Convenience bootstrap from the same origin:

curl -fsSL ${PUBLIC_URL}/releases/bootstrap.sh | sudo bash

Offline form after copying releases/ to the VPS:

sudo bash install.sh --backend ${PUBLIC_URL} --binary ./${AGENT_NAME} --sha256 ${AGENT_SHA}

Existing wg0.conf is left unchanged. A backup is written under /var/lib/family-vpn/backups/.
--update also backs up the previous agent binary and rolls back if the new service fails.

Checksums:
$(cat "$OUT/SHA256SUMS")
EOF

echo "release $VERSION written to $OUT"
echo "pubkey fingerprint: $PUB_FP"
echo "one command:"
echo "$ONE_COMMAND"
echo "update command:"
echo "$UPDATE_COMMAND"
